// Optional runtime override of translations (set briefly while generating a PDF)
let I18N_OVERRIDE: Record<InvoiceLocale, Record<string, string>> | undefined;

export function buildPaymentInvoicePdf(data: PaymentInvoicePdfData): Buffer {
    return buildStyledInvoicePdf(data);
}

function buildStyledInvoicePdf(data: PaymentInvoicePdfData): Buffer {
    const locale = resolveInvoiceLocale(data.locale);
    // If caller provided translations (for example frontend can pass this.$t map),
    // use them as override while generating this PDF.
    if (data.translations) {
        I18N_OVERRIDE = data.translations;
    }

    const pageWidth = 595;
    const pageHeight = 842;
    const contentInstructions: string[] = [];

    const invoiceNumber = normalizeInvoiceValue(data.invoiceNumber, buildFallbackInvoiceNumber(data.id, data.createdAt), locale);
    const conceptText = resolveCommercialConcept(data.concept, data.paymentType, locale);
    const paymentTypeText = formatPaymentTypeLabel(data.paymentType, locale);
    const productTypeText = formatProductTypeLabel(data.productType, locale);
    const billingCycleText = formatBillingCycleLabel(data.billingCycle, locale);
    const methodText = formatMethodLabel(data.method, locale);

    const totalCents = Math.max(0, Math.floor(Number(data.amountCents) || 0));
    const taxRatePercent = normalizeTaxRatePercent(data.taxRatePercent);
    const subtotalCents = taxRatePercent > 0 ? Math.round(totalCents / (1 + taxRatePercent / 100)) : totalCents;
    const taxesCents = Math.max(0, totalCents - subtotalCents);

    const amountText = formatInvoiceAmount(totalCents, data.currency || "EUR", locale);
    const subtotalText = formatInvoiceAmount(subtotalCents, data.currency || "EUR", locale);
    const taxesText = formatInvoiceAmount(taxesCents, data.currency || "EUR", locale);
    const dateText = formatInvoiceDate(data.createdAt || Date.now(), locale);
    const statusText = toTitle(data.status || "unknown");
    const statusColor = resolveInvoiceStatusColor(data.status || "");
    const discountCents = Math.max(0, Math.floor(Number(data.discountCents) || 0));
    const nubemTokensDiscountCents = Math.max(0, Math.floor(Number(data.nubemTokensDiscountCents) || 0));
    const discountText = discountCents > 0 ? `-${formatInvoiceAmount(discountCents, data.currency || "EUR", locale)}` : "";
    const nubemTokensDiscountText =
        nubemTokensDiscountCents > 0 ? `-${formatInvoiceAmount(nubemTokensDiscountCents, data.currency || "EUR", locale)}` : "";

    const issuerName = normalizeInvoiceValue(data.issuerName, "Nubemsystems", locale);
    const issuerWebsite = normalizeInvoiceValue(data.issuerWebsite, t(locale, "notAvailable"), locale);
    const issuerEmail = normalizeInvoiceValue(data.issuerEmail, t(locale, "notAvailable"), locale);

    const clientName = normalizeInvoiceValue(data.clientName, t(locale, "customer"), locale);
    const clientEmail = normalizeInvoiceValue(data.clientEmail, t(locale, "notAvailable"), locale);
    const clientReference = normalizeInvoiceValue(data.clientReference, data.id || t(locale, "notAvailable"), locale);

    const colorNavy = "#1C2659"; // --color-brand-primary
    const colorSecondary = "#5A7BAE"; // --color-brand-secondary
    const colorTeal = "#007885"; // --color-brand-secondary-alt
    const colorSurface = "#FFFFFF"; // --color-bg-surface
    const colorPageBg = "#FFFFFF"; // page background
    const colorBorder = "#E5E5E5"; // hairline border
    const colorMuted = "#6B7280"; // --color-text-muted
    const colorWhite = "#FFFFFF";

    const pushLabelValue = (
        label: string,
        value: string,
        labelX: number,
        valueRight: number,
        y: number,
        labelFont: PdfFont = "F1",
        labelSize = 9.5,
        valueFont: PdfFont = "F1",
        valueSize = 9.5,
        labelColor = colorMuted,
        valueColor = colorNavy,
    ) => {
        pushPdfText(contentInstructions, label, labelX, y, labelFont, labelSize, labelColor);
        pushPdfTextRight(contentInstructions, value, valueRight, y, valueFont, valueSize, valueColor);
    };

    const pushLabelAndWrappedValue = (
        label: string,
        value: string,
        labelX: number,
        valueX: number,
        y: number,
        valueFont: PdfFont,
        valueSize: number,
        maxLines: number,
    ): number => {
        pushPdfText(contentInstructions, label, labelX, y, "F1", 9.5, colorMuted);

        const maxChars = Math.max(18, Math.floor(176 / (valueSize * 0.55)));
        const wrapped = wrapPdfText(value, maxChars, maxLines, locale);
        for (let i = 0; i < wrapped.length; i++) {
            pushPdfText(contentInstructions, wrapped[i], valueX, y - i * 12, valueFont, valueSize, colorNavy);
        }

        return Math.max(24, wrapped.length * 12 + 12);
    };

    const pageMarginX = 0;
    const pageMarginTop = 0;
    const pageMarginBottom = 0;
    const contentRight = pageWidth - pageMarginX;

    // Page background
    pushPdfFilledRect(contentInstructions, 0, 0, pageWidth, pageHeight, colorPageBg);

    // Main invoice card
    const mainCardX = pageMarginX;
    const mainCardBottom = pageMarginBottom;
    const mainCardWidth = contentRight - pageMarginX;
    const mainCardTop = pageHeight - pageMarginTop;
    const mainCardHeight = mainCardTop - mainCardBottom;
    const cardInnerPaddingX = 12;
    const cardInnerLeft = mainCardX + cardInnerPaddingX;
    const cardInnerRight = mainCardX + mainCardWidth - cardInnerPaddingX;
    const centerX = mainCardX + mainCardWidth / 2;

    const headerTitleY = mainCardTop - 30;
    const headerSubtitleY = mainCardTop - 50;
    const headerInvoiceNumberY = mainCardTop - 68;
    const headerDividerY = mainCardTop - 88;
    const summaryLabelY = mainCardTop - 114;
    const summaryConceptY = mainCardTop - 136;
    const summaryMetaDateY = mainCardTop - 130;
    const summaryMetaMethodY = mainCardTop - 150;
    const summaryMetaStatusY = mainCardTop - 170;
    const summaryDividerY = mainCardTop - 186;
    const partySectionTopY = mainCardTop - 200;
    const partySectionBottomY = mainCardTop - 292;
    const partyTitleY = mainCardTop - 208;
    const partyNameY = mainCardTop - 226;
    const partyMetaLine1Y = mainCardTop - 260;
    const partyMetaLine2Y = mainCardTop - 276;
    const detailsDividerY = mainCardTop - 306;
    const detailsHeadingY = mainCardTop - 330;
    const detailsStartY = mainCardTop - 358;
    const breakdownTop = mainCardTop - 342;
    const footerDividerY = mainCardBottom + 64;

    pushPdfFilledRect(contentInstructions, mainCardX, mainCardBottom, mainCardWidth, mainCardHeight, colorSurface);
    pushPdfFilledRect(contentInstructions, mainCardX, mainCardTop - 4, mainCardWidth, 4, colorTeal);

    // ===========================================================================
    // CABECERA DE FACTURA
    // Incluye: titulo, subtitulo y numero de factura.
    // ===========================================================================
    pushPdfText(contentInstructions, t(locale, "invoiceTitle"), cardInnerLeft, headerTitleY, "F2", 22, colorNavy);
    pushPdfText(contentInstructions, t(locale, "invoiceSubtitle"), cardInnerLeft, headerSubtitleY, "F1", 10.5, colorMuted);
    pushPdfText(contentInstructions, `${t(locale, "invoiceNumber")}: ${invoiceNumber}`, cardInnerLeft, headerInvoiceNumberY, "F1", 10, colorMuted);
    pushPdfLine(contentInstructions, cardInnerLeft, headerDividerY, cardInnerRight, headerDividerY, colorBorder, 1);

    // ===========================================================================
    // RESUMEN DE PAGO
    // Incluye: concepto comercial + fecha, metodo y estado.
    // ===========================================================================
    const conceptLines = wrapPdfText(conceptText, 36, 2, locale);
    pushPdfText(contentInstructions, t(locale, "paymentSummary"), cardInnerLeft, summaryLabelY, "F2", 9.5, colorSecondary);
    for (let lineIndex = 0; lineIndex < conceptLines.length; lineIndex++) {
        pushPdfText(contentInstructions, conceptLines[lineIndex], cardInnerLeft, summaryConceptY - lineIndex * 18, "F2", 15.5, colorNavy);
    }

    const summaryMetaLabelX = Math.max(centerX + 8, cardInnerRight - 238);
    const summaryMetaValueX = summaryMetaLabelX + 58;
    pushPdfText(contentInstructions, `${t(locale, "date")}:`, summaryMetaLabelX, summaryMetaDateY, "F2", 10, colorMuted);
    pushPdfText(contentInstructions, dateText, summaryMetaValueX, summaryMetaDateY, "F1", 10, colorNavy);
    pushPdfText(contentInstructions, `${t(locale, "method")}:`, summaryMetaLabelX, summaryMetaMethodY, "F2", 10, colorMuted);
    pushPdfText(contentInstructions, methodText, summaryMetaValueX, summaryMetaMethodY, "F1", 10, colorNavy);
    pushPdfText(contentInstructions, `${t(locale, "status")}:`, summaryMetaLabelX, summaryMetaStatusY, "F2", 10, colorMuted);
    pushPdfText(contentInstructions, statusText, summaryMetaValueX, summaryMetaStatusY, "F1", 10, statusColor);

    pushPdfLine(contentInstructions, cardInnerLeft, summaryDividerY, cardInnerRight, summaryDividerY, colorBorder, 1);

    // ===========================================================================
    // BLOQUE IDENTIDAD (EMISOR / CLIENTE)
    // Dos columnas paralelas separadas por una linea vertical.
    // ===========================================================================
    const issuerColumnX = cardInnerLeft;
    const clientColumnX = centerX + 14;
    pushPdfLine(contentInstructions, centerX, partySectionBottomY, centerX, partySectionTopY, colorBorder, 1);

    // ----- EMISOR -----
    pushPdfText(contentInstructions, t(locale, "issuer"), issuerColumnX, partyTitleY, "F2", 9.5, colorSecondary);
    const issuerNameLines = wrapPdfText(issuerName, 34, 2, locale);
    for (let lineIndex = 0; lineIndex < issuerNameLines.length; lineIndex++) {
        pushPdfText(contentInstructions, issuerNameLines[lineIndex], issuerColumnX, partyNameY - lineIndex * 14, "F2", 11, colorNavy);
    }
    pushPdfText(contentInstructions, `${t(locale, "website")}: ${issuerWebsite}`, issuerColumnX, partyMetaLine1Y, "F1", 9, colorMuted);
    pushPdfText(contentInstructions, `${t(locale, "email")}: ${issuerEmail}`, issuerColumnX, partyMetaLine2Y, "F1", 9, colorMuted);

    // ----- CLIENTE -----
    pushPdfText(contentInstructions, t(locale, "client"), clientColumnX, partyTitleY, "F2", 9.5, colorSecondary);
    const clientNameLines = wrapPdfText(clientName, 34, 2, locale);
    for (let lineIndex = 0; lineIndex < clientNameLines.length; lineIndex++) {
        pushPdfText(contentInstructions, clientNameLines[lineIndex], clientColumnX, partyNameY - lineIndex * 14, "F2", 11, colorNavy);
    }
    pushPdfText(contentInstructions, `${t(locale, "email")}: ${clientEmail}`, clientColumnX, partyMetaLine1Y, "F1", 9, colorMuted);
    pushPdfText(contentInstructions, `${t(locale, "clientRef")}: ${clientReference}`, clientColumnX, partyMetaLine2Y, "F1", 9, colorMuted);

    pushPdfLine(contentInstructions, cardInnerLeft, detailsDividerY, cardInnerRight, detailsDividerY, colorBorder, 1);

    // ===========================================================================
    // DETALLE DE FACTURA (TABLA IZQUIERDA)
    // Metadatos de la transaccion: ID, servicio, metodo, tipo, ciclo, etc.
    // ===========================================================================
    const quantity = Math.max(1, Math.floor(Number(data.quantity) || 1));

    const detailRows: Array<{ label: string; value: string; font: PdfFont; size: number; maxLines: number }> = [
        { label: t(locale, "paymentId"), value: data.id || "", font: "F1", size: 9.5, maxLines: 2 },
        { label: t(locale, "service"), value: conceptText, font: "F1", size: 10, maxLines: 2 },
        ...(quantity > 1
            ? [{ label: t(locale, "quantity"), value: `${quantity}`, font: "F1" as PdfFont, size: 10, maxLines: 1 }]
            : []),
        { label: t(locale, "paymentMethod"), value: methodText, font: "F1", size: 10, maxLines: 1 },
        { label: t(locale, "paymentType"), value: paymentTypeText, font: "F1", size: 10, maxLines: 1 },
        { label: t(locale, "productType"), value: productTypeText, font: "F1", size: 10, maxLines: 1 },
        { label: t(locale, "billingCycle"), value: billingCycleText, font: "F1", size: 10, maxLines: 1 },
        ...(discountCents > 0 ? [{ label: t(locale, "discount"), value: discountText, font: "F2" as PdfFont, size: 10, maxLines: 1 }] : []),
        ...(nubemTokensDiscountCents > 0
            ? [{ label: t(locale, "nubemTokens"), value: nubemTokensDiscountText, font: "F2" as PdfFont, size: 10, maxLines: 1 }]
            : []),
        { label: t(locale, "status"), value: statusText, font: "F2", size: 10, maxLines: 1 },
    ];

    pushPdfText(contentInstructions, t(locale, "invoiceDetails"), cardInnerLeft, detailsHeadingY, "F2", 14, colorNavy);

    const tableLabelX = cardInnerLeft;
    const tableValueX = cardInnerLeft + 102;
    let rowY = detailsStartY;
    for (const row of detailRows) {
        const rowHeight = pushLabelAndWrappedValue(row.label, row.value, tableLabelX, tableValueX, rowY, row.font, row.size, row.maxLines);
        rowY -= rowHeight;
    }

    // ===========================================================================
    // TOTAL PAGADO (DESGLOSE DERECHA)
    // Base, subtotal, descuentos, impuestos, ecuacion y total final.
    // ===========================================================================
    const breakdownX = centerX + 16;
    const breakdownWidth = cardInnerRight - breakdownX;

    // Compute the unit price and total base price.
    // basePriceCents from the service is the per-unit price.
    const unitPriceCents = (() => {
        const explicit = Number(data.basePriceCents);
        if (Number.isFinite(explicit) && explicit > 0) return Math.max(0, Math.round(explicit));
        return Math.max(0, subtotalCents + discountCents + nubemTokensDiscountCents);
    })();
    const totalBaseCents = unitPriceCents * quantity;
    const totalBaseText = formatInvoiceAmount(totalBaseCents, data.currency || "EUR", locale);

    const bdLabelX = breakdownX + 16;
    const bdValueRight = breakdownX + breakdownWidth - 16;
    let breakdownRowY = breakdownTop - 82;

    // Cabecera visual del bloque de total pagado (sin caja de fondo).
    pushPdfText(contentInstructions, t(locale, "totalPaid"), bdLabelX, breakdownTop - 24, "F2", 9.5, colorSecondary);
    pushPdfText(contentInstructions, amountText, bdLabelX, breakdownTop - 48, "F2", 18, colorNavy);
    pushPdfLine(contentInstructions, bdLabelX, breakdownTop - 60, bdValueRight, breakdownTop - 60, colorBorder, 1);

    // Linea de precio unitario: si hay mas de un asiento, mostrar cantidad x precio unitario.
    if (quantity > 1) {
        const unitPriceText = formatInvoiceAmount(unitPriceCents, data.currency || "EUR", locale);
        pushLabelValue(t(locale, "unitPrice"), `${quantity} x ${unitPriceText}`, bdLabelX, bdValueRight, breakdownRowY, "F1", 9.5, "F1", 9.5, colorMuted, colorNavy);
        breakdownRowY -= 18;
    }

    // Linea de base: total antes de descuentos (unitPrice x quantity si aplica).
    pushLabelValue(t(locale, "basePrice"), totalBaseText, bdLabelX, bdValueRight, breakdownRowY, "F1", 9.5, "F1", 9.5, colorMuted, colorNavy);
    breakdownRowY -= 18;

    // Linea de subtotal: solo si hay impuestos (si no, es igual al total).
    if (taxRatePercent > 0) {
        pushLabelValue(t(locale, "subtotal"), subtotalText, bdLabelX, bdValueRight, breakdownRowY, "F1", 9.5, "F1", 9.5, colorMuted, colorNavy);
        breakdownRowY -= 18;
    }

    if (discountCents > 0) {
        pushLabelValue(t(locale, "discount"), discountText, bdLabelX, bdValueRight, breakdownRowY, "F1", 9.5, "F1", 9.5, colorMuted, colorNavy);
        breakdownRowY -= 18;
    }

    if (nubemTokensDiscountCents > 0) {
        pushLabelValue(t(locale, "nubemTokens"), nubemTokensDiscountText, bdLabelX, bdValueRight, breakdownRowY, "F1", 9.5, "F1", 9.5, colorMuted, colorNavy);
        breakdownRowY -= 18;
    }

    pushLabelValue(t(locale, "taxes"), taxesText, bdLabelX, bdValueRight, breakdownRowY, "F1", 9.5, "F1", 9.5, colorMuted, colorNavy);
    breakdownRowY -= 14;

    pushPdfLine(contentInstructions, bdLabelX, breakdownRowY, bdValueRight, breakdownRowY, colorBorder, 1);
    pushPdfText(contentInstructions, t(locale, "total"), bdLabelX, breakdownRowY - 20, "F2", 11, colorNavy);
    pushPdfTextRight(contentInstructions, amountText, bdValueRight, breakdownRowY - 20, "F2", 11, colorNavy);

    // ===========================================================================
    // PIE DE FACTURA
    // Aviso legal y marca de plataforma.
    // ===========================================================================
    pushPdfLine(contentInstructions, cardInnerLeft, footerDividerY, cardInnerRight, footerDividerY, colorBorder, 1);

    const footerCenterY = footerDividerY / 2;

    // Right half: generatedFooter text
    const rightChars = Math.max(20, Math.floor((cardInnerRight - centerX) / 4.8));
    const footerLines = wrapPdfText(t(locale, "generatedFooter"), rightChars, 4, locale);
    let footerTextY = footerCenterY + (footerLines.length - 1) * 5 + 3;
    for (const line of footerLines) {
        pushPdfText(contentInstructions, line, centerX + 4, footerTextY, "F1", 8, colorMuted);
        footerTextY -= 11;
    }

    // Left half: logo centered vertically
    if (logoData) {
        const targetWidth = 130;
        const s = targetWidth / logoData.width;
        const lw = Math.round(logoData.width * s);
        const lh = Math.round(logoData.height * s);
        const logoY = footerCenterY - Math.round(lh / 2);
        contentInstructions.push("q");
        contentInstructions.push(`${toPdfNumber(lw)} 0 0 ${toPdfNumber(lh)} ${toPdfNumber(cardInnerLeft)} ${toPdfNumber(logoY)} cm`);
        contentInstructions.push("/Img1 Do");
        contentInstructions.push("Q");
    }

    const content = contentInstructions.join("\n");
    const contentLength = Buffer.byteLength(content, "binary");

    let objects: string[];

    if (logoData) {
        const rgbHex = logoData.rgbCompressed.toString("hex");
        const alphaHex = logoData.alphaCompressed.toString("hex");

        objects = [
            "<< /Type /Catalog /Pages 2 0 R >>",
            "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
            `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 4 0 R /F2 5 0 R /F3 6 0 R >> /XObject << /Img1 7 0 R >> >> /Contents 9 0 R >>`,
            "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>",
            "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>",
            "<< /Type /Font /Subtype /Type1 /BaseFont /Courier /Encoding /WinAnsiEncoding >>",
            `<< /Type /XObject /Subtype /Image /Width ${logoData.width} /Height ${logoData.height} /ColorSpace /DeviceRGB /BitsPerComponent 8 /Filter [/ASCIIHexDecode /FlateDecode] /Length ${rgbHex.length} /SMask 8 0 R >>\nstream\n${rgbHex}\nendstream`,
            `<< /Type /XObject /Subtype /Image /Width ${logoData.width} /Height ${logoData.height} /ColorSpace /DeviceGray /BitsPerComponent 8 /Filter [/ASCIIHexDecode /FlateDecode] /Length ${alphaHex.length} >>\nstream\n${alphaHex}\nendstream`,
            `<< /Length ${contentLength} >>\nstream\n${content}\nendstream`,
        ];
    } else {
        objects = [
            "<< /Type /Catalog /Pages 2 0 R >>",
            "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
            "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 4 0 R /F2 5 0 R /F3 6 0 R >> >> /Contents 7 0 R >>",
            "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>",
            "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>",
            "<< /Type /Font /Subtype /Type1 /BaseFont /Courier /Encoding /WinAnsiEncoding >>",
            `<< /Length ${contentLength} >>\nstream\n${content}\nendstream`,
        ];
    }

    let pdf = "%PDF-1.4\n";
    const offsets: number[] = [];

    for (let i = 0; i < objects.length; i++) {
        offsets.push(Buffer.byteLength(pdf, "binary"));
        pdf += `${i + 1} 0 obj\n${objects[i]}\nendobj\n`;
    }

    const startXref = Buffer.byteLength(pdf, "binary");
    pdf += `xref\n0 ${objects.length + 1}\n`;
    pdf += "0000000000 65535 f \n";
    for (const offset of offsets) {
        pdf += `${offset.toString().padStart(10, "0")} 00000 n \n`;
    }
    pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${startXref}\n%%EOF`;

    const result = Buffer.from(pdf, "binary");

    // Clear override after generation to avoid leaking into subsequent calls
    I18N_OVERRIDE = undefined;
    return result;
}

function pushPdfFilledRect(instructions: string[], x: number, y: number, width: number, height: number, fillColorHex: string): void {
    instructions.push(`${hexToPdfColor(fillColorHex)} rg`);
    instructions.push(`${toPdfNumber(x)} ${toPdfNumber(y)} ${toPdfNumber(width)} ${toPdfNumber(height)} re f`);
}

function pushPdfLine(
    instructions: string[],
    fromX: number,
    fromY: number,
    toX: number,
    toY: number,
    strokeColorHex: string,
    lineWidth: number,
): void {
    instructions.push(`${hexToPdfColor(strokeColorHex)} RG`);
    instructions.push(`${toPdfNumber(lineWidth)} w`);
    instructions.push(`${toPdfNumber(fromX)} ${toPdfNumber(fromY)} m ${toPdfNumber(toX)} ${toPdfNumber(toY)} l S`);
}

function pushPdfText(
    instructions: string[],
    text: string,
    x: number,
    y: number,
    font: PdfFont,
    size: number,
    colorHex: string,
): void {
    const safeText = normalizePdfText(text, 420);
    instructions.push(`${hexToPdfColor(colorHex)} rg`);
    instructions.push(`BT /${font} ${toPdfNumber(size)} Tf 1 0 0 1 ${toPdfNumber(x)} ${toPdfNumber(y)} Tm (${encodePdfTextForLiteralString(safeText)}) Tj ET`);
}

function pushPdfTextRight(
    instructions: string[],
    text: string,
    rightX: number,
    y: number,
    font: PdfFont,
    size: number,
    colorHex: string,
): void {
    const safeText = normalizePdfText(text, 420);
    const width = estimatePdfTextWidth(safeText, font, size);
    pushPdfText(instructions, safeText, rightX - width, y, font, size, colorHex);
}

function estimatePdfTextWidth(text: string, font: PdfFont, size: number): number {
    // Approximate glyph advances per 1000 units for the standard Type1 fonts.
    const isMono = font === "F3"; // Courier
    let totalPer1000 = 0;

    for (const character of text) {
        if (isMono) {
            totalPer1000 += 600;
            continue;
        }

        if (character >= "0" && character <= "9") {
            totalPer1000 += 556;
        } else if (character === " ") {
            totalPer1000 += 278;
        } else if (".,:;'|!".includes(character)) {
            totalPer1000 += 278;
        } else if (character >= "A" && character <= "Z") {
            totalPer1000 += 667;
        } else if (character >= "a" && character <= "z") {
            totalPer1000 += 528;
        } else {
            totalPer1000 += 556;
        }
    }

    return (totalPer1000 / 1000) * size;
}

function formatInvoiceDate(timestamp: number, locale: InvoiceLocale): string {
    const safeTimestamp = Number.isFinite(timestamp) && timestamp > 0 ? timestamp : Date.now();
    const safeDate = new Date(safeTimestamp);

    try {
        const formatted = new Intl.DateTimeFormat(getIntlLocale(locale), {
            day: "2-digit",
            month: "short",
            year: "numeric",
            hour: "2-digit",
            minute: "2-digit",
            timeZone: "UTC",
            hour12: false,
        }).format(safeDate);

        return `${formatted} UTC`;
    } catch (_ex) {
        return safeDate.toISOString();
    }
}

function formatInvoiceAmount(amountCents: number, currency: string, locale: InvoiceLocale): string {
    const safeAmount = Number.isFinite(amountCents) ? amountCents : 0;
    const safeCurrency = ((currency || "EUR") + "").trim().toUpperCase();

    try {
        return new Intl.NumberFormat(getIntlLocale(locale), {
            style: "currency",
            currency: safeCurrency.length === 3 ? safeCurrency : "EUR",
            maximumFractionDigits: 2,
        }).format(safeAmount / 100);
    } catch (_ex) {
        return `${(safeAmount / 100).toFixed(2)} ${safeCurrency || "EUR"}`;
    }
}

