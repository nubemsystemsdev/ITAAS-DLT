function wrapPdfText(value: string, maxCharsPerLine: number, maxLines: number, locale: InvoiceLocale): string[] {
    const safeText = normalizePdfText(value, 420);
    const maxChars = Math.max(8, Math.floor(maxCharsPerLine || 8));
    const limitLines = Math.max(1, Math.floor(maxLines || 1));
    const wrapped: string[] = [];

    const pushToken = (token: string) => {
        if (!token) {
            return;
        }

        const line = wrapped.length ? wrapped[wrapped.length - 1] : "";

        if (!line) {
            if (!wrapped.length) {
                wrapped.push(token);
                return;
            }

            wrapped[wrapped.length - 1] = token;
            return;
        }

        const candidate = `${line} ${token}`;
        if (candidate.length <= maxChars) {
            wrapped[wrapped.length - 1] = candidate;
            return;
        }

        wrapped.push(token);
    };

    const splitLongToken = (token: string): string[] => {
        if (token.length <= maxChars) {
            return [token];
        }

        const chunks: string[] = [];
        let index = 0;
        while (index < token.length) {
            chunks.push(token.slice(index, index + maxChars));
            index += maxChars;
        }
        return chunks;
    };

    for (const token of safeText.split(/\s+/g).filter((part) => !!part)) {
        const tokenChunks = splitLongToken(token);
        for (const chunk of tokenChunks) {
            if (!wrapped.length) {
                wrapped.push("");
            }
            pushToken(chunk);
        }
    }

    const normalized = wrapped.filter((line) => !!line);
    if (!normalized.length) {
        return [t(locale, "notAvailable")];
    }

    if (normalized.length <= limitLines) {
        return normalized;
    }

    const cropped = normalized.slice(0, limitLines);
    const lastLine = cropped[cropped.length - 1];
    if (lastLine.length >= 1) {
        cropped[cropped.length - 1] = `${lastLine.slice(0, Math.max(0, lastLine.length - 1))}\u2026`;
    }
    return cropped;
}

function normalizePdfText(text: string, maxLength: number): string {
    const normalized = ((text || "") + "")
        .normalize("NFKC")
        .replace(/\s+/g, " ")
        .trim();

    if (!normalized) {
        return "";
    }

    if (normalized.length <= maxLength) {
        return normalized;
    }

    return `${normalized.slice(0, Math.max(0, maxLength - 1))}\u2026`;
}

function encodePdfTextForLiteralString(text: string): string {
    let encoded = "";

    for (const character of text) {
        const byte = unicodeToWinAnsiByte(character);

        if (byte === 0x28 || byte === 0x29 || byte === 0x5C) {
            encoded += `\\${String.fromCharCode(byte)}`;
            continue;
        }

        if (byte >= 0x20 && byte <= 0x7E) {
            encoded += String.fromCharCode(byte);
            continue;
        }

        encoded += `\\${byte.toString(8).padStart(3, "0")}`;
    }

    return encoded;
}

function unicodeToWinAnsiByte(character: string): number {
    if (WIN_ANSI_CHAR_TO_BYTE[character] !== undefined) {
        return WIN_ANSI_CHAR_TO_BYTE[character];
    }

    const code = character.codePointAt(0) || 0x3F;

    if (code >= 0x20 && code <= 0x7E) {
        return code;
    }

    if (code >= 0xA0 && code <= 0xFF) {
        return code;
    }

    return 0x3F;
}

function hexToPdfColor(hexColor: string): string {
    const normalized = ((hexColor || "") + "")
        .replace("#", "")
        .trim();
    const safeHex = /^[\da-fA-F]{6}$/.test(normalized) ? normalized : "000000";

    const r = parseInt(safeHex.slice(0, 2), 16) / 255;
    const g = parseInt(safeHex.slice(2, 4), 16) / 255;
    const b = parseInt(safeHex.slice(4, 6), 16) / 255;

    return `${r.toFixed(3)} ${g.toFixed(3)} ${b.toFixed(3)}`;
}

function toPdfNumber(value: number): string {
    if (!Number.isFinite(value)) {
        return "0";
    }

    return (Math.round(value * 100) / 100).toFixed(2);
}

function buildFallbackInvoiceNumber(paymentId: string, createdAt: number): string {
    const year = new Date(createdAt || Date.now()).getUTCFullYear() || new Date().getUTCFullYear();
    const normalized = ((paymentId || "") + "")
        .replace(/[^a-zA-Z0-9]/g, "")
        .toUpperCase();
    const suffix = normalized.slice(-8).padStart(8, "0");

    return `NUBEM-${year}-${suffix}`;
}

function normalizeTaxRatePercent(taxRatePercent: number | undefined): number {
    const value = Number(taxRatePercent || 0);
    if (!Number.isFinite(value)) {
        return 0;
    }

    return Math.min(100, Math.max(0, Math.round(value * 100) / 100));
}

function toTitle(raw: string): string {
    const normalized = (raw || "")
        .split(/[_\s-]+/g)
        .map((part) => part.trim())
        .filter((part) => !!part)
        .map((part) => part.charAt(0).toUpperCase() + part.slice(1).toLowerCase());

    return normalized.join(" ");
}

function resolveInvoiceLocale(locale: string | undefined): InvoiceLocale {
    const normalized = ((locale || "") + "").trim().toLowerCase();
    return normalized.startsWith("es") ? "es" : "en";
}

function getIntlLocale(locale: InvoiceLocale): string {
    return locale === "es" ? "es-ES" : "en-US";
}

function t(locale: InvoiceLocale, key: string): string {
    // Prefer runtime override if provided (allows frontend to pass this.$t mappings)
    if (I18N_OVERRIDE && I18N_OVERRIDE[locale] && I18N_OVERRIDE[locale][key]) {
        return I18N_OVERRIDE[locale][key];
    }

    return INVOICE_I18N[locale][key] || INVOICE_I18N.en[key] || key;
}
